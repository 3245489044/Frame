
#nullable enable
using TConfig;
using UniversalMiddleware.Abstractions;
using FrameworkLayoutPosition = UniversalMiddleware.Abstractions.LayoutPosition;

namespace UniversalMiddleware.Layout;

public static class LayoutPositionConverter
{
    public static FrameworkLayoutPosition Convert(TConfig.LayoutPosition src)
    {
        double left = src.Left;
        double top = src.Top;

        if (left < 0 && top < 0 && (src.X >= 0 || src.Y >= 0))
        {
            left = src.X;
            top = src.Y;
        }

        if (src.Bottom >= 0 && top < 0)
            top = -src.Bottom;
        if (src.Right >= 0 && left < 0)
            left = -src.Right;

        return new FrameworkLayoutPosition
        {
            Left = left,
            Top = top,
            Width = src.Width,
            Height = src.Height
        };
    }

    public static ElementDefinition ToElementDefinition(ControlConfig config)
    {
        var definition = new ElementDefinition
        {
            ControlName = config.Name,
            Position = new FrameworkLayoutPosition(),
            SizeConstraints = new SizeConstraints
            {
                MinWidth = config.Width > 0 ? config.Width : 0,
                MinHeight = config.Height > 0 ? config.Height : 0
            }
        };

        if (config.Layout != null)
        {
            definition.Position = Convert(config.Layout);
        }

        return definition;
    }

    public static LayoutDefinition ToLayoutDefinition(IEnumerable<ControlConfig> configs, string name = "AutoGenerated")
    {
        var definition = new LayoutDefinition
        {
            Name = name,
            Type = global::UniversalLayoutFramework.LayoutType.Proportional,
            Elements = new List<ElementDefinition>()
        };

        foreach (var config in configs)
        {
            if (config.Layout != null)
            {
                definition.Elements.Add(new ElementDefinition
                {
                    ControlName = config.Name,
                    Position = Convert(config.Layout),
                    SizeConstraints = new SizeConstraints
                    {
                        MinWidth = config.Width > 0 ? config.Width : 0,
                        MinHeight = config.Height > 0 ? config.Height : 0
                    }
                });
            }
        }

        return definition;
    }
}
