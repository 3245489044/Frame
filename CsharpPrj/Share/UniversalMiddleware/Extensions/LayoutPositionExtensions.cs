
#nullable enable
using TConfig;
using UniversalMiddleware.Abstractions;
using FrameworkLayoutPosition = UniversalMiddleware.Abstractions.LayoutPosition;

namespace UniversalMiddleware.Extensions;

public static class LayoutPositionExtensions
{
    public static FrameworkLayoutPosition ToFrameworkPosition(this TConfig.LayoutPosition src)
    {
        double left = src.Left;
        double top = src.Top;

        if (left < 0 && top < 0 && (src.X >= 0 || src.Y >= 0))
        {
            left = src.X;
            top = src.Y;
        }

        if (src.Bottom >= 0 && top < 0)
            top = -src.Bottom;
        if (src.Right >= 0 && left < 0)
            left = -src.Right;

        return new FrameworkLayoutPosition
        {
            Left = left,
            Top = top,
            Width = src.Width,
            Height = src.Height
        };
    }

    public static LayoutDefinition ToLayoutDefinition(this IEnumerable<ControlConfig> configs, string name = "AutoGenerated")
    {
        var definition = new LayoutDefinition
        {
            Name = name,
            Type = global::UniversalLayoutFramework.LayoutType.Proportional,
            Elements = new List<ElementDefinition>()
        };

        foreach (var config in configs)
        {
            if (config.Layout != null)
            {
                definition.Elements.Add(new ElementDefinition
                {
                    ControlName = config.Name,
                    Position = config.Layout.ToFrameworkPosition(),
                    SizeConstraints = new SizeConstraints
                    {
                        MinWidth = config.Width > 0 ? config.Width : 0,
                        MinHeight = config.Height > 0 ? config.Height : 0
                    }
                });
            }
        }

        return definition;
    }
}
