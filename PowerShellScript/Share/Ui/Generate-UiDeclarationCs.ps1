#requires -Version 7.0
<#
.SYNOPSIS
    UI 声明强类型代码生成器 —— ui-declaration.generated.json → GeneratedUiDeclaration.g.cs。

.DESCRIPTION
    产物契约（单源）= Frame\PowerShellScript\Share\Ui\Generate-UiDeclaration.ps1 的输出。
    本器只做「数据 → 常量/初始化器」的机械转写（禁逻辑、禁手改）；稳定序 = 产物序。
    新鲜度由 Check-GeneratedArtifactsDrift 兜底（存在 / 哨兵 / 复算逐字比对）。

.PARAMETER InputFile
    中间产物路径（缺省 = Agent.Ui 声明目录内的 ui-declaration.generated.json）。

.PARAMETER OutFile
    输出 .cs 路径（缺省 = 同目录 GeneratedUiDeclaration.g.cs）。
#>
[CmdletBinding()]
param(
    [string]$InputFile = '',
    [string]$OutFile = ''
)

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..\..\..\..')).Path
$declDir = Join-Path $root 'Projects\Plug\Agent\src\Agent.Ui\Ui\Views\Declaration'
if (-not $InputFile) { $InputFile = Join-Path $declDir 'ui-declaration.generated.json' }
if (-not $OutFile) { $OutFile = Join-Path $declDir 'GeneratedUiDeclaration.g.cs' }
if (-not (Test-Path -LiteralPath $InputFile)) { Write-Error "产物缺失：$InputFile"; exit 2 }

$document = Get-Content -LiteralPath $InputFile -Raw -Encoding UTF8 | ConvertFrom-Json
if ([string]$document.schema -ne 'ui-declaration-v1') { Write-Error "schema 非法：$($document.schema)"; exit 2 }

function Cs-String([object]$value) {
    if ($null -eq $value) { return 'null' }
    $s = [string]$value
    $s = $s.Replace('\', '\\').Replace('"', '\"').Replace("`r", '\r').Replace("`n", '\n').Replace("`t", '\t')
    return '"' + $s + '"'
}

function Cs-Array([object[]]$values) {
    if ($null -eq $values -or $values.Count -eq 0) { return 'System.Array.Empty<string>()' }
    $items = @($values | ForEach-Object { Cs-String $_ })
    return 'new[] { ' + ($items -join ', ') + ' }'
}

