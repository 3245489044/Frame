[void]$sb.AppendLine('namespace Agent.Launcher')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    /// <summary>UI 声明生成视图（纯数据 + 指纹；禁业务逻辑）。</summary>')
[void]$sb.AppendLine('    internal static class GeneratedUiDeclaration')
[void]$sb.AppendLine('    {')
[void]$sb.AppendLine('        /// <summary>产物 schema 哨兵。</summary>')
