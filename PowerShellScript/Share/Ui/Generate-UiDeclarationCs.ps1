[void]$sb.AppendLine('        /// <summary>声明全字段指纹（改容器/迁移/生命周期必变）。</summary>')
[void]$sb.AppendLine('        public const string Fingerprint = ' + (Cs-String $document.fingerprint) + ';')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('        /// <summary>页面视图宿主名。</summary>')
[void]$sb.AppendLine('        public const string Root = ' + (Cs-String $document.root) + ';')
[void]$sb.AppendLine('')

[void]$sb.AppendLine('        /// <summary>位置属性表（声明序；未声明 ⇒ 查表未命中，调用方显式可见化）。</summary>')
[void]$sb.AppendLine('        public static readonly UiDeclarationLocRecord[] Locs =')
[void]$sb.AppendLine('        {')
foreach ($loc in @($document.locs)) {
    $matrix = 'null'
    if ($null -ne $loc.matrix) {
        $pairs = @()
        foreach ($p in $loc.matrix.PSObject.Properties) {
            $pairs += ('[' + (Cs-String $p.Name) + '] = ' + (Cs-String $p.Value))
        }
        if ($pairs.Count -gt 0) {
            $matrix = 'new System.Collections.Generic.Dictionary<string, string>(System.StringComparer.OrdinalIgnoreCase) { ' + ($pairs -join ', ') + ' }'
        }
    }
    [void]$sb.AppendLine('            new UiDeclarationLocRecord { Loc = ' + (Cs-String $loc.loc) +
        ', Kind = ' + (Cs-String $loc.kind) +
        ', Value = ' + (Cs-String $loc.value) +
        ', OnMiss = ' + (Cs-String $loc.onMiss) +
        ', Matrix = ' + $matrix + ' },')
}
[void]$sb.AppendLine('        };')
[void]$sb.AppendLine('')

[void]$sb.AppendLine('        /// <summary>派生容器集（壳槽 + 声明区域；门禁只读本段）。</summary>')
[void]$sb.AppendLine('        public static readonly UiDeclarationContainerRecord[] Containers =')
[void]$sb.AppendLine('        {')
foreach ($c in @($document.containers)) {
    [void]$sb.AppendLine('            new UiDeclarationContainerRecord { View = ' + (Cs-String $c.view) +
        ', Key = ' + (Cs-String $c.key) +
        ', Owner = ' + (Cs-String $c.owner) +
        ', Role = ' + (Cs-String $c.role) + ' },')
}
[void]$sb.AppendLine('        };')
[void]$sb.AppendLine('')

[void]$sb.AppendLine('        /// <summary>视图程序（渲染序 = 产物序）。</summary>')
[void]$sb.AppendLine('        public static readonly UiDeclarationViewRecord[] Views =')
[void]$sb.AppendLine('        {')
foreach ($v in @($document.views)) {
    $regions = @($v.regions | ForEach-Object {
            'new UiDeclarationRegionRecord { Kind = ' + (Cs-String $_.kind) + ', Key = ' + (Cs-String $_.key) +
            ', Role = ' + (Cs-String $_.role) + ', Loc = ' + (Cs-String $_.loc) + ' }'
        })
    $migrations = @($v.stateMigration | ForEach-Object {
            'new UiDeclarationMigrationRecord { Kind = ' + (Cs-String $_.kind) + ', Key = ' + (Cs-String $_.key) + ' }'
        })
    $rules = @()
    if ($null -ne $v.regionRules) {
        foreach ($r in $v.regionRules.PSObject.Properties) {
            $rules += ('new UiDeclarationRuleRecord { Region = ' + (Cs-String $r.Name) +
                ', Grouping = ' + (Cs-String $r.Value.grouping) +
                ', SuppressHeader = ' + $(if ($r.Value.suppressHeader) { 'true' } else { 'false' }) +
                ', Fields = ' + (Cs-Array @($r.Value.fields)) + ' }')
        }
    }
    $fieldList = @()
    if ($null -ne $v.fields) {
        foreach ($f in $v.fields.PSObject.Properties) {
            $fieldList += ('new UiDeclarationFieldRecord { Name = ' + (Cs-String $f.Name) +
                ', Visible = ' + $(if ($f.Value.visible) { 'true' } else { 'false' }) + ' }')
        }
    }
    $ruleExpr = if ($rules.Count -eq 0) { 'System.Array.Empty<UiDeclarationRuleRecord>()' } else { 'new[] { ' + ($rules -join ', ') + ' }' }
    $fieldExpr = if ($fieldList.Count -eq 0) { 'System.Array.Empty<UiDeclarationFieldRecord>()' } else { 'new[] { ' + ($fieldList -join ', ') + ' }' }
    $regionExpr = if ($regions.Count -eq 0) { 'System.Array.Empty<UiDeclarationRegionRecord>()' } else { 'new[] { ' + ($regions -join ', ') + ' }' }
    $migrationExpr = if ($migrations.Count -eq 0) { 'System.Array.Empty<UiDeclarationMigrationRecord>()' } else { 'new[] { ' + ($migrations -join ', ') + ' }' }

    [void]$sb.AppendLine('            new UiDeclarationViewRecord')
    [void]$sb.AppendLine('            {')
    [void]$sb.AppendLine('                View = ' + (Cs-String $v.view) + ',')
    [void]$sb.AppendLine('                ViewType = ' + (Cs-String $v.viewType) + ',')
    [void]$sb.AppendLine('                TypeKey = ' + (Cs-String $v.typeKey) + ',')
    [void]$sb.AppendLine('                ScopeKey = ' + (Cs-String $v.scopeKey) + ',')
    [void]$sb.AppendLine('                Snapshot = ' + (Cs-String $v.snapshot) + ',')
    [void]$sb.AppendLine('                Lifecycle = ' + (Cs-String $v.lifecycle) + ',')
    [void]$sb.AppendLine('                Regions = ' + $regionExpr + ',')
    [void]$sb.AppendLine('                StateMigrations = ' + $migrationExpr + ',')
    [void]$sb.AppendLine('                ContentDomain = ' + (Cs-String $v.content.domain) + ',')
    [void]$sb.AppendLine('                ContentScope = ' + (Cs-String $v.content.scope) + ',')
    [void]$sb.AppendLine('                ContentFold = ' + (Cs-String $v.content.fold) + ',')
    [void]$sb.AppendLine('                AnchorChain = ' + (Cs-Array @($v.anchor.chain)) + ',')
    [void]$sb.AppendLine('                AnchorOnUnknown = ' + (Cs-String $v.anchor.onUnknown) + ',')
    [void]$sb.AppendLine('                AnchorContainer = ' + (Cs-String $v.anchor.container) + ',')
    [void]$sb.AppendLine('                PanelRegion = ' + (Cs-String $v.panel.region) + ',')
    [void]$sb.AppendLine('                PanelDomain = ' + (Cs-String $v.panel.domain) + ',')
    [void]$sb.AppendLine('                PanelMode = ' + (Cs-String $v.panel.mode) + ',')
    [void]$sb.AppendLine('                RegionRules = ' + $ruleExpr + ',')
    [void]$sb.AppendLine('                Fields = ' + $fieldExpr + ',')
    [void]$sb.AppendLine('                FactPriority = ' + (Cs-Array @($v.factPriority)) + ',')
    [void]$sb.AppendLine('                Sidebar = ' + (Cs-String $v.sidebar) + ',')
    [void]$sb.AppendLine('                Composer = ' + (Cs-String $v.composer) + ',')
    [void]$sb.AppendLine('                ActorLevel = ' + (Cs-String $v.actorLevel) + ',')
    [void]$sb.AppendLine('                TitleLoc = ' + (Cs-String $v.titleLoc) + ',')
    [void]$sb.AppendLine('                SubtitleLoc = ' + (Cs-String $v.subtitleLoc) + ',')
    [void]$sb.AppendLine('                GatherView = ' + (Cs-String $v.gatherView) + ',')
    [void]$sb.AppendLine('                Board = ' + (Cs-String $v.board) + ',')
    [void]$sb.AppendLine('                EmptyShortCircuit = ' + $(if ($v.emptyShortCircuit) { 'true' } else { 'false' }) + ',')
    [void]$sb.AppendLine('                SectionFilter = ' + (Cs-String $v.sectionFilter) + ',')
    [void]$sb.AppendLine('                RenderMode = ' + (Cs-String $v.renderMode) + ',')
    [void]$sb.AppendLine('                SelectorOrder = ' + [int]$v.selectorOrder + ',')
    [void]$sb.AppendLine('                LabelLoc = ' + (Cs-String $v.labelLoc) + ',')
    [void]$sb.AppendLine('                RoundVisible = ' + $(if ($v.roundVisible) { 'true' } else { 'false' }) + ',')
    [void]$sb.AppendLine('            },')
}
[void]$sb.AppendLine('        };')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('}')

$dir = Split-Path $OutFile -Parent
if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
$utf8NoBom = New-Object System.Text.UTF8Encoding $false
[System.IO.File]::WriteAllText($OutFile, $sb.ToString(), $utf8NoBom)
Write-Host ("[OK] 已生成 GeneratedUiDeclaration：views={0} containers={1} locs={2}" -f @($document.views).Count, @($document.containers).Count, @($document.locs).Count) -ForegroundColor Green
Write-Host ("  写出: {0}" -f $OutFile) -ForegroundColor Green
exit 0
