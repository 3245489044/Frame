<#
.SYNOPSIS
    常量生成器（G5）—— 从 declared-manifest.constants 生成 C# partial 成员视图。

.DESCRIPTION
    真源 = Config\**\*.ushar 的 [Const] 单元（经 DeclaredBundleBuilder 单点编译 → declared-manifest.json）。
    本器把 manifest.constants 展开为「同名 partial 类型 + public const 成员」，供编译期引用与手抄漂移检测；
    生成物禁手改（新鲜度由 Check-GeneratedArtifactsDrift 兜底）。

    口径（逐字，禁改写）：
      · target / 成员名 / 值表达式原样输出（禁 Pascal↔kebab 转换、禁引号/转义改写）；
      · 同 target 的多个单元（按 valueType 拆分）合并为**一个**类型分部；
      · 序 = 单元 target 升序 → valueType 升序 → 成员声明序（同输入两次输出逐字节相同）。

    类型存在性（C9，属生成期判据；内核不承担领域坐标）：-SourceRoot 内须存在同 kind 的 partial 类型，
    否则报错且不写产物（禁生成不可编译代码）。

.PARAMETER Manifest
    declared-manifest.json 路径（仓库相对或绝对）。

.PARAMETER OutFile
    输出 .cs 路径（缺省 = Agent.Contract\Generated\GeneratedContractConstants.g.cs）。

.PARAMETER SourceRoot
    目标类型所在源码根（缺省 = Projects\Plug\Agent\src\Agent.Contract）。

.PARAMETER Check
    只校验（生成到临时文件并与现有产物逐字节比较；不一致 ⇒ 退出码 1，不写盘）。
#>
[CmdletBinding()]
param(
    [string]$Manifest = 'Projects\Plug\Agent\src\Agent.Core\Declared\declared-manifest.json',
    [string]$OutFile = '',
    [string]$SourceRoot = 'Projects\Plug\Agent\src\Agent.Contract',
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..\..\..\..')).Path

function Resolve-Repo([string]$Path) {
    if ([System.IO.Path]::IsPathRooted($Path)) { return $Path }
    return (Join-Path $root $Path)
}

$manifestAbs = Resolve-Repo $Manifest
if (-not (Test-Path -LiteralPath $manifestAbs)) { Write-Error "manifest 缺失：$manifestAbs"; exit 2 }

if (-not $OutFile) { $OutFile = 'Projects\Plug\Agent\src\Agent.Contract\Generated\GeneratedContractConstants.g.cs' }
$outAbs = Resolve-Repo $OutFile
$sourceAbs = Resolve-Repo $SourceRoot

$m = Get-Content -LiteralPath $manifestAbs -Raw -Encoding UTF8 | ConvertFrom-Json
$units = @($m.constants)

# ---- 类型存在性（C9）：target 存在同 kind 的 partial 类型 ----
$errors = New-Object System.Collections.Generic.List[string]
$checked = @{}
foreach ($unit in $units) {
    if ($checked.ContainsKey($unit.target)) { continue }
    $checked[$unit.target] = $true

    $parts = $unit.target.Split('.')
    $typeName = $parts[-1]
    $pattern = "\b(class|record|struct)\s+" + [regex]::Escape($typeName) + "\b"
    $hit = $null
    if (Test-Path -LiteralPath $sourceAbs) {
        $hit = Get-ChildItem -LiteralPath $sourceAbs -Recurse -File -Filter *.cs |
            Select-String -Pattern $pattern |
            Select-Object -First 1
    }

    if ($null -eq $hit) {
        $errors.Add("US8209 [Const] $($unit.target)：源码根内未找到同 kind 的类型 '$typeName'（SourceRoot=$SourceRoot）")
        continue
    }
    if ($hit.Line -notmatch '\bpartial\b') {
        $errors.Add(("US8209 [Const] {0}：源类型 '{1}' 未声明 partial（{2}:{3}）" -f $unit.target, $typeName, $hit.Path, $hit.LineNumber))
    }
}

if ($errors.Count -gt 0) {
    $errors | ForEach-Object { Write-Host $_ -ForegroundColor Red }
    exit 3
}

# ---- 形态映射（生成侧必须与源类型一致）----
function Get-Declaration([string]$kind, [string]$modifier) {
    switch ($kind) {
        'class' {
            switch ($modifier) {
                'static'   { return 'public static partial class' }
                'sealed'   { return 'public sealed partial class' }
                'abstract' { return 'public abstract partial class' }
                default    { return 'public partial class' }
            }
        }
        'record' {
            if ($modifier -eq 'sealed') { return 'public sealed partial record' }
            return 'public partial record'
        }
        'struct' { return 'public partial struct' }
        default  { throw "unsupported kind: $kind" }
    }
}

# ---- 生成（同 target 合并；序 = target → valueType → 成员声明序）----
$byTarget = [ordered]@{}
$orderedUnits = $units | Sort-Object -Property @{ Expression = { $_.target } }, @{ Expression = { $_.valueType } }
foreach ($unit in $orderedUnits) {
    if (-not $byTarget.Contains($unit.target)) {
        $byTarget[$unit.target] = [pscustomobject]@{
            Target   = $unit.target
            Kind     = $unit.kind
            Modifier = $unit.modifier
            Members  = New-Object System.Collections.Generic.List[object]
        }
    }
    foreach ($member in @($unit.members)) {
        $byTarget[$unit.target].Members.Add([pscustomobject]@{
            Name      = $member.name
            Value     = $member.value
            ValueType = $unit.valueType
        })
    }
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('// <auto-generated/>')
[void]$sb.AppendLine('// 此文件由 Generate-ContractConstants.ps1 从 declared-manifest.constants 生成，禁止手工编辑。')
[void]$sb.AppendLine('// 真源 = Config\**\*.ushar 的 [Const] 单元（经 DeclaredBundleBuilder 单点编译）。')

$currentNamespace = $null
foreach ($entry in $byTarget.Values) {
    $parts = $entry.Target.Split('.')
    $typeName = $parts[-1]
    $ns = ($parts[0..($parts.Length - 2)] -join '.')

    if ($ns -ne $currentNamespace) {
        if ($null -ne $currentNamespace) { [void]$sb.AppendLine('}') }
        [void]$sb.AppendLine("namespace $ns")
        [void]$sb.AppendLine('{')
        $currentNamespace = $ns
    }

    [void]$sb.AppendLine('    ' + (Get-Declaration $entry.Kind $entry.Modifier) + ' ' + $typeName)
    [void]$sb.AppendLine('    {')
    foreach ($member in $entry.Members) {
        [void]$sb.AppendLine('        public const ' + $member.ValueType + ' ' + $member.Name + ' = ' + $member.Value + ';')
    }
    [void]$sb.AppendLine('    }')
    [void]$sb.AppendLine('')
}
if ($null -ne $currentNamespace) { [void]$sb.AppendLine('}') }

$content = $sb.ToString()
$utf8NoBom = New-Object System.Text.UTF8Encoding $false
$memberCount = (($byTarget.Values | ForEach-Object { $_.Members.Count }) | Measure-Object -Sum).Sum

if ($Check) {
    if (-not (Test-Path -LiteralPath $outAbs)) { Write-Host '[DRIFT] 产物缺失' -ForegroundColor Red; exit 1 }
    $existing = [System.IO.File]::ReadAllText($outAbs)
    if ($existing -ne $content) { Write-Host '[DRIFT] 产物与生成结果不一致（重跑本器）' -ForegroundColor Red; exit 1 }
    Write-Host ('[OK] 常量产物一致：units={0} members={1}' -f $byTarget.Count, $memberCount) -ForegroundColor Green
    exit 0
}

$dir = Split-Path $outAbs -Parent
if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
[System.IO.File]::WriteAllText($outAbs, $content, $utf8NoBom)
Write-Host ('[OK] 已生成 GeneratedContractConstants：units={0} members={1}' -f $byTarget.Count, $memberCount) -ForegroundColor Green
Write-Host ("  写出: {0}" -f $outAbs) -ForegroundColor Green
exit 0
