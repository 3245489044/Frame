<#
.SYNOPSIS
    声明常量生成器（G2）—— 从冻结产物 manifest 生成 C# 常量视图（GeneratedDeclaredContracts.g.cs）。

.DESCRIPTION
    真源 = Config\**\*.ushar（经 DeclaredBundleBuilder 单点编译 → declared-manifest.json）。
    本器把 manifest 的 functions / flowIds / ports 展开为 C# 常量视图，供编译期引用与手抄漂移检测；
    生成物禁手改（新鲜度由 Check-GeneratedArtifactsDrift 兜底）。

.PARAMETER Manifest
    declared-manifest.json 路径（仓库相对或绝对）。

.PARAMETER OutFile
    输出 .cs 路径（缺省 = Agent.Contract\WorkflowFunction\GeneratedDeclaredContracts.g.cs）。
#>
[CmdletBinding()]
param(
    [string]$Manifest = 'Projects\Plug\Agent\src\Agent.Core\Declared\declared-manifest.json',
    [string]$OutFile = ''
)

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..\..\..\..')).Path

$manifestAbs = if ([System.IO.Path]::IsPathRooted($Manifest)) { $Manifest } else { Join-Path $root $Manifest }
if (-not (Test-Path -LiteralPath $manifestAbs)) { Write-Error "manifest 缺失：$manifestAbs"; exit 2 }

if (-not $OutFile) { $OutFile = Join-Path $root 'Projects\Plug\Agent\src\Agent.Contract\WorkflowFunction\GeneratedDeclaredContracts.g.cs' }

$m = Get-Content -LiteralPath $manifestAbs -Raw -Encoding UTF8 | ConvertFrom-Json

function Format-Array([string[]]$Items) {
    $q = @($Items | ForEach-Object { '            "' + $_ + '"' })
    return ($q -join ",`r`n")
}

$fn = @($m.functions)
$flowIds = @($m.flows | ForEach-Object { $_.flowId } | Sort-Object -Unique)
$ports = @(@($m.ports.inports) + @($m.ports.outports) | Sort-Object -Unique)

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('// <auto-generated/>')
[void]$sb.AppendLine('// 此文件由 Generate-DeclaredConstants.ps1 从 declared-manifest.json 生成，禁止手工编辑。')
[void]$sb.AppendLine('// 真源 = Config\**\*.ushar（经 DeclaredBundleBuilder 单点编译）。')
[void]$sb.AppendLine('namespace Agent.Contract.WorkflowFunction')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    /// <summary>冻结声明的编译期常量视图（G2）：fn 集 / 流号集 / 端口集（从产物生成，登记手抄漂移）。</summary>')
[void]$sb.AppendLine('    public static class GeneratedDeclaredContracts')
[void]$sb.AppendLine('    {')
[void]$sb.AppendLine('        /// <summary>源指纹（declared-manifest 的 SourceFingerprint）。</summary>')
[void]$sb.AppendLine('        public const string SourceFingerprint = "' + $m.fingerprint + '";')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('        /// <summary>全部 [Node] fn= 集（manifest.functions）。</summary>')
[void]$sb.AppendLine('        public static readonly string[] Functions =')
[void]$sb.AppendLine('        {')
[void]$sb.AppendLine((Format-Array $fn))
[void]$sb.AppendLine('        };')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('        /// <summary>全部 [Flow] 流号集（manifest.flows[].flowId）。</summary>')
[void]$sb.AppendLine('        public static readonly string[] FlowIds =')
[void]$sb.AppendLine('        {')
[void]$sb.AppendLine((Format-Array $flowIds))
[void]$sb.AppendLine('        };')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('        /// <summary>全部端口键集（inports ∪ outports）。</summary>')
[void]$sb.AppendLine('        public static readonly string[] Ports =')
[void]$sb.AppendLine('        {')
[void]$sb.AppendLine((Format-Array $ports))
[void]$sb.AppendLine('        };')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('}')

$dir = Split-Path $OutFile -Parent
if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
$utf8NoBom = New-Object System.Text.UTF8Encoding $false
[System.IO.File]::WriteAllText($OutFile, $sb.ToString(), $utf8NoBom)
Write-Host ("[OK] 已生成 GeneratedDeclaredContracts：fn={0} flowIds={1} ports={2}" -f $fn.Count, $flowIds.Count, $ports.Count) -ForegroundColor Green
Write-Host ("  写出: {0}" -f $OutFile) -ForegroundColor Green
exit 0
